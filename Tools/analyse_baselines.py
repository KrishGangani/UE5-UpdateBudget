"""P01 UpdateBudget - analyse a baseline batch for the hypotheses that need more than the summary table.

Usage: python -I analyse_baselines.py <batch> [split_round]   e.g. 2026-11-21_002119_baseline 2
       split_round adds a drift check: rounds 1..split vs the later rounds.
Writes Benchmarks/Summaries/<batch>_analysis.md. Reads only the batch's manifest and raw CSVs (never edits them).

What it computes, per (config, N), as the median across runs [min-max across runs]:
  H1  dispatch overhead: B1 (batched ticks) minus B0 GameThreadTime median, i.e. what tick batching saves.
  H4  phase-aligned interval spikes: the autocorrelation of UpdatesRun per frame at lags 6 (0.1 s) and 30 (0.5 s)
      at the fixed 60 Hz step, plus UpdatesRun max / median. A periodic baseline shows high values at those lags.
  H6  re-tune cost: UBBaseline/GameThread/Retune median and p99 (ms) and IntervalChanges per frame (B2, B3).
Per-run GameThreadTime and UpdatesRun statistics come from the manifest (run_bench.py computed them with the same
csv_stats code); the CSV is read only for what the manifest doesn't hold: the per-frame series and the driver columns.
"""
import json
import math
import os
import statistics
import sys

TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, TOOLS)
import csv_stats  # noqa: E402

PROJECT = os.path.dirname(TOOLS)
RAW = os.path.join(PROJECT, "Benchmarks", "Raw")
SUMMARIES = os.path.join(PROJECT, "Benchmarks", "Summaries")

UPDATES = "UpdateBudget/UpdatesRun"
RETUNE = "UBBaseline/GameThread/Retune"
CHANGES = "UBBaseline/IntervalChanges"
LAGS = (6, 30)   # frames at the fixed 60 Hz step: 0.1 s and 0.5 s, the two band intervals


def column(header: list[str], data: list[list[str]], name: str) -> list[float]:
    """A column's values, or [] if this capture doesn't have it (B0/B1 have no driver columns)."""
    return csv_stats.column_values(header, data, name) if name in header else []


def autocorrelation(series: list[float], lag: int) -> float:
    n = len(series)
    if n <= lag + 1:
        return math.nan
    mean = statistics.fmean(series)
    variance = sum((x - mean) ** 2 for x in series)
    if variance == 0:
        return 0.0
    return sum((series[i] - mean) * (series[i + lag] - mean) for i in range(n - lag)) / variance


def cell(values: list[float], digits: int = 3) -> str:
    """Median [min-max] of the per-run values, NaN skipped."""
    values = [v for v in values if not math.isnan(v)]
    if not values:
        return "n/a"
    return f"{statistics.median(values):.{digits}f} [{min(values):.{digits}f}-{max(values):.{digits}f}]"


def col(group: list[dict], key: str, digits: int = 3) -> str:
    return cell([g[key] for g in group], digits)


def table(title: str, intro: str, headers: list[str]) -> list[str]:
    lines = ["", title, ""] + ([intro, ""] if intro else [])
    return lines + ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]


def run_metrics(record: dict, header: list[str], data: list[list[str]]) -> dict:
    stats = record["stats"]
    updates = column(header, data, UPDATES)
    retune = column(header, data, RETUNE)
    changes = column(header, data, CHANGES)
    retune_stats = csv_stats.summarize(retune) if retune else {"median": math.nan, "p99": math.nan}
    return {
        "run": record.get("run", 0),
        "gt_median": stats["GameThreadTime"]["median"],
        "upd_median": stats[UPDATES]["median"],
        "upd_max": stats[UPDATES]["max"],
        **{f"ac{lag}": autocorrelation(updates, lag) for lag in LAGS},
        "retune_median": retune_stats["median"],
        "retune_p99": retune_stats["p99"],
        "changes_mean": statistics.fmean(changes) if changes else math.nan,
    }


def main() -> int:
    batch = sys.argv[1]
    with open(os.path.join(RAW, batch + "_manifest.json"), encoding="utf-8") as handle:
        manifest = json.load(handle)

    by_work: dict[tuple, list[dict]] = {}
    for record in manifest["runs"]:
        path = os.path.join(RAW, record["name"] + ".csv")
        if record.get("priming") or "stats" not in record or not os.path.exists(path):
            continue
        header, data, _, finalised = csv_stats.load_capture(path)
        if finalised:
            by_work.setdefault((record["config"], record.get("work"), record["agents"]), []).append(run_metrics(record, header, data))

    works = {w for _, w, _ in by_work}
    if len(works) > 1:
        print("this analysis expects one workload per batch; found", sorted(works, key=str))
        return 1
    per_combo = {(c, n): group for (c, _, n), group in by_work.items()}   # one workload: key by (config, N)
    rows = sorted(per_combo.items())

    lines = [f"# Baseline analysis: {batch}", "",
             "Generated by `Tools/analyse_baselines.py` from the raw CSVs listed in the batch manifest. "
             "Each cell: median across runs [min-max across runs]. Runs per combination: "
             + ", ".join(f"{c}/N={n}: {len(group)}" for (c, n), group in rows), ""]

    lines += table("## H1 · What engine tick batching saves (B0 - B1, GameThreadTime median, ms)", "",
                   ["N", "B0", "B1", "B0 - B1 (per-run medians paired by run index)"])[1:]
    for n in sorted({n for _, n in per_combo}):
        b0, b1 = per_combo.get(("B0", n), []), per_combo.get(("B1", n), [])
        # Pair by the run index both configs have (same round), never by list position: a run with a missing or
        # unfinished capture is skipped, and position pairing would then mix rounds.
        b1_by_run = {r["run"]: r for r in b1}
        diffs = [a["gt_median"] - b1_by_run[a["run"]]["gt_median"] for a in b0 if a["run"] in b1_by_run]
        lines.append(f"| {n} | {col(b0, 'gt_median')} | {col(b1, 'gt_median')} | {cell(diffs)} |")

    lag_text = " and ".join(f"lag {lag} ({lag / 60:.1f} s)" for lag in LAGS)
    lines += table("## H4 · Periodic update spikes (UpdatesRun per frame)",
                   f"Autocorrelation of the per-frame update count at {lag_text}, and max / median. "
                   "A value near 1 means the load repeats with that period, a sign of phase-aligned tick intervals.",
                   ["Config", "N", "UpdatesRun median", "max", "max / median"] + [f"autocorr lag {lag}" for lag in LAGS])
    for (c, n), group in rows:
        ratio = [g["upd_max"] / g["upd_median"] for g in group if g["upd_median"]]
        lines.append(f"| {c} | {n} | {col(group, 'upd_median', 0)} | {col(group, 'upd_max', 0)} | {cell(ratio, 2)} | "
                     + " | ".join(col(group, f"ac{lag}", 2) for lag in LAGS) + " |")

    lines += table("## H6 · Re-tune cost of the smarter native baselines",
                   "`UBBaseline/GameThread/Retune` is the driver's own per-frame work (B2: distance loop; B3: Significance Manager "
                   "update + callbacks). The tick manager's cooling-down list cost is inside GameThreadTime, not in this column.",
                   ["Config", "N", "Retune median (ms)", "Retune p99 (ms)", "Interval changes per frame (mean)"])
    for (c, n), group in rows:
        if c in ("B2", "B3"):
            lines.append(f"| {c} | {n} | {col(group, 'retune_median')} | {col(group, 'retune_p99')} | {col(group, 'changes_mean', 2)} |")

    if len(sys.argv) > 2:
        # Drift check: split the rounds in two (e.g. "2" = rounds 1-2 vs 3+) and compare GameThreadTime medians.
        split = int(sys.argv[2])
        lines += table(f"## Drift check · rounds 1-{split} vs rounds {split + 1}+ (GameThreadTime median, ms)",
                       "Interleaving spreads slow drifts over every config; this table shows whether the machine itself "
                       "changed between the two halves of the batch.",
                       ["Config", "N", f"rounds 1-{split}", f"rounds {split + 1}+", "later - earlier"])
        for (c, n), group in rows:
            early = [g["gt_median"] for g in group if g["run"] <= split]
            late = [g["gt_median"] for g in group if g["run"] > split]
            if early and late:
                lines.append(f"| {c} | {n} | {cell(early)} | {cell(late)} | {statistics.median(late) - statistics.median(early):+.3f} |")

    os.makedirs(SUMMARIES, exist_ok=True)
    out = os.path.join(SUMMARIES, batch + "_analysis.md")
    with open(out, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    print("analysis:", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
